package com.example.datingsite.model;

/**
 * Стан зв'язку між поточним користувачем та анкетою, яку він переглядає.
 * Використовується на сторінці анкети в елементі th:switch.
 */
public enum ConnectionStatus {

    /** Користувач переглядає власну анкету. */
    SELF,
    /** Запрошень між користувачами немає. */
    NONE,
    /** Поточний користувач надіслав запрошення, відповіді ще немає. */
    INVITATION_SENT,
    /** Поточний користувач отримав запрошення і ще не відповів. */
    INVITATION_RECEIVED,
    /** Запрошення прийняте - взаємна симпатія. */
    MATCHED,
    /** Запрошення відхилене. */
    DECLINED
}
